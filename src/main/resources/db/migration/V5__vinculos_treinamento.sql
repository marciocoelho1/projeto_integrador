-- Vínculos colaborador x treinamento (item 5): situação de execução do treinamento por colaborador
-- e validade calculada no backend a partir de treinamentos.validade_meses + data_conclusao.
-- Não editar esta migração depois de aplicada.

CREATE TABLE colaborador_treinamentos (
  id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  colaborador_id INT NOT NULL REFERENCES colaboradores (id),
  treinamento_id INT NOT NULL REFERENCES treinamentos (id),
  data_conclusao DATE,
  status VARCHAR(20) NOT NULL
      CHECK (status IN ('Concluído', 'Em Andamento', 'Pendente')),
  validade DATE,
  criado_em TIMESTAMPTZ NOT NULL DEFAULT now(),
  CONSTRAINT colaborador_treinamentos_colaborador_treinamento_key
      UNIQUE (colaborador_id, treinamento_id)
);

CREATE INDEX colaborador_treinamentos_colaborador_idx
    ON colaborador_treinamentos (colaborador_id);

CREATE INDEX colaborador_treinamentos_treinamento_idx
    ON colaborador_treinamentos (treinamento_id);
