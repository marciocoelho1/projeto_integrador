-- Item 6: cargos, matriz LNT (treinamentos obrigatórios por cargo), certificações de colaborador
-- e turmas de reciclagem. Não editar esta migração depois de aplicada.

CREATE TABLE cargos (
  id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome VARCHAR(120) NOT NULL UNIQUE,
  setor VARCHAR(120) NOT NULL,
  status VARCHAR(20) NOT NULL
      CHECK (status IN ('Ativo', 'Inativo'))
);

CREATE TABLE cargo_treinamentos (
  id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  cargo_id INT NOT NULL REFERENCES cargos (id),
  treinamento_id INT NOT NULL REFERENCES treinamentos (id),
  obrigatorio BOOLEAN NOT NULL DEFAULT true,
  CONSTRAINT cargo_treinamentos_cargo_treinamento_key
      UNIQUE (cargo_id, treinamento_id)
);

CREATE INDEX cargo_treinamentos_cargo_idx ON cargo_treinamentos (cargo_id);
CREATE INDEX cargo_treinamentos_treinamento_idx ON cargo_treinamentos (treinamento_id);

CREATE TABLE certificacoes (
  id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  colaborador_id INT NOT NULL REFERENCES colaboradores (id),
  treinamento_id INT NOT NULL REFERENCES treinamentos (id),
  instituicao VARCHAR(150) NOT NULL,
  carga_horaria VARCHAR(30) NOT NULL,
  emitida_em DATE NOT NULL,
  validade DATE NOT NULL,
  arquivo_url VARCHAR(300),
  CONSTRAINT certificacoes_periodo_check
      CHECK (validade >= emitida_em)
);

CREATE INDEX certificacoes_colaborador_idx ON certificacoes (colaborador_id);
CREATE INDEX certificacoes_treinamento_idx ON certificacoes (treinamento_id);

CREATE TABLE turmas_reciclagem (
  id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  treinamento_id INT NOT NULL REFERENCES treinamentos (id),
  instrutor VARCHAR(150) NOT NULL,
  data_agendada DATE NOT NULL,
  vagas INT NOT NULL
      CHECK (vagas >= 0),
  status VARCHAR(20) NOT NULL
      CHECK (status IN ('Agendada', 'Concluída', 'Cancelada'))
);

CREATE INDEX turmas_reciclagem_treinamento_idx ON turmas_reciclagem (treinamento_id);
