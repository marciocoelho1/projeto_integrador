-- Usuários do sistema, grupos de acesso e matriz de módulos liberados.
-- Os seis módulos e os dois grupos são dados de referência do sistema (não são demonstração):
-- sem eles a matriz de acessos da tela Configurações não tem o que liberar.
-- As contas de demonstração ficam em db/demo (perfil "demo"), nunca aqui.
-- O primeiro usuário de um banco novo é criado por POST /api/auth/bootstrap (só funciona com a
-- tabela usuarios vazia) — evita senha padrão versionada no repositório.

CREATE TABLE modulos (
  chave VARCHAR(40) PRIMARY KEY,
  titulo VARCHAR(120) NOT NULL,
  detalhe VARCHAR(255) NOT NULL
);

CREATE TABLE grupos_acesso (
  id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nomenclatura VARCHAR(120) NOT NULL UNIQUE,
  finalidade VARCHAR(255) NOT NULL
);

CREATE TABLE grupo_modulos (
  grupo_id INT NOT NULL REFERENCES grupos_acesso (id) ON DELETE CASCADE,
  modulo_chave VARCHAR(40) NOT NULL REFERENCES modulos (chave),
  PRIMARY KEY (grupo_id, modulo_chave)
);

CREATE TABLE usuarios (
  id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome_completo VARCHAR(150) NOT NULL,
  login VARCHAR(60) NOT NULL UNIQUE,
  email VARCHAR(180) NOT NULL UNIQUE,
  cpf VARCHAR(14) NOT NULL UNIQUE,
  senha_hash VARCHAR(100) NOT NULL,
  grupo_id INT NOT NULL REFERENCES grupos_acesso (id),
  status VARCHAR(20) NOT NULL
      CHECK ( status IN ('Ativo', 'Inativo')),
  criado_em TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE sessoes (
  id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  token VARCHAR(64) NOT NULL UNIQUE,
  usuario_id INT NOT NULL REFERENCES usuarios (id) ON DELETE CASCADE,
  criada_em TIMESTAMPTZ NOT NULL,
  expira_em TIMESTAMPTZ NOT NULL
);

CREATE TABLE redefinicoes_senha (
  id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  usuario_id INT NOT NULL REFERENCES usuarios (id) ON DELETE CASCADE,
  token VARCHAR(64) NOT NULL UNIQUE,
  criada_em TIMESTAMPTZ NOT NULL,
  expira_em TIMESTAMPTZ NOT NULL,
  usada_em TIMESTAMPTZ
);

