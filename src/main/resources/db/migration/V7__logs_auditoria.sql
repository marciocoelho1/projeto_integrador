-- Auditoria persistida (item 8). A tabela guarda as operações de escrita da API, registradas
-- automaticamente pelo AuditoriaInterceptor, e também lançamentos manuais do frontend
-- (POST /api/auditoria). usuario_id é opcional: o login ainda não tem sessão e algumas rotas
-- públicas podem gerar evento sem usuário identificado.
-- Não editar esta migração depois de aplicada.

CREATE TABLE logs_auditoria (
  id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  data_hora TIMESTAMPTZ NOT NULL,
  usuario_id INT NULL REFERENCES usuarios (id),
  usuario_nome VARCHAR(150) NULL,
  modulo VARCHAR(60) NOT NULL,
  acao VARCHAR(20) NOT NULL
      CHECK ( acao IN ('CRIACAO', 'EDICAO', 'EXCLUSAO', 'ACESSO', 'ALERTA') ),
  descricao VARCHAR(300) NOT NULL,
  metodo VARCHAR(10) NOT NULL,
  caminho VARCHAR(300) NOT NULL,
  status_http INT NOT NULL
);

CREATE INDEX logs_auditoria_data_hora_idx ON logs_auditoria (data_hora DESC);
