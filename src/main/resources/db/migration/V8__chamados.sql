-- Chamados de suporte (item 9): ajuda e reporte de erro abertos pelos usuários.
-- usuario_id é opcional para permitir lançamentos de demonstração sem vínculo; em uso normal o
-- solicitante vem da sessão (ContextoUsuario). concluido_em só é preenchido em 'Concluída'.
-- Não editar esta migração depois de aplicada.

CREATE TABLE chamados (
  id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  tipo VARCHAR(30) NOT NULL
      CHECK ( tipo IN ('Ajuda', 'Erro') ),
  descricao VARCHAR(500) NOT NULL,
  usuario_id INT NULL REFERENCES usuarios (id),
  solicitante VARCHAR(150) NOT NULL,
  status VARCHAR(20) NOT NULL
      CHECK ( status IN ('Em andamento', 'Concluída', 'Cancelada') ),
  aberto_em TIMESTAMPTZ NOT NULL,
  concluido_em TIMESTAMPTZ NULL
);

CREATE INDEX chamados_status_idx ON chamados (status);
CREATE INDEX chamados_usuario_idx ON chamados (usuario_id);
