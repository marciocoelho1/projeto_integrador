-- Entregas de EPI: registra a saída de estoque de um EPI para um colaborador.
-- Cada linha é o termo de entrega assinado: guarda a quantidade, o colaborador, o EPI e os
-- dados do CA vigentes NO ATO da entrega (ca_no_ato / validade_ca_no_ato), denormalizados de
-- propósito para que o histórico não mude se o EPI for editado depois.
-- O saldo em epis.quantidade é abatido na mesma transação da entrega e estornado no DELETE.
-- Não editar esta migração depois de aplicada.

CREATE TABLE epi_entregas (
  id INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  colaborador_id INT NOT NULL REFERENCES colaboradores (id),
  epi_id INT NOT NULL REFERENCES epis (id),
  quantidade INT NOT NULL CHECK (quantidade > 0),
  data_entrega DATE NOT NULL,
  assinatura VARCHAR(150) NOT NULL,
  ca_no_ato VARCHAR(30) NOT NULL,
  validade_ca_no_ato DATE NOT NULL,
  registrado_em TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- Acelera o filtro do portal do colaborador (GET /api/entregas-epis?colaboradorId=...).
CREATE INDEX epi_entregas_colaborador_idx ON epi_entregas (colaborador_id);
